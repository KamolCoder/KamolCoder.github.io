#!/usr/bin/env node
/*
 * Static build: renders _build/template.html into one HTML page per language,
 * plus sitemap.xml and robots.txt. Translations come from assets/js/i18n.js.
 *
 *   node _build/build.js
 *
 * Folders starting with "_" are not published by GitHub Pages (Jekyll), so the
 * template and this script stay out of the live site.
 */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const SITE = "https://kamolcoder.github.io"; // change when a custom domain is connected
const ROOT = path.resolve(__dirname, "..");
const LANGS = {
  ru: { out: "index.html", path: "/", base: "", ogLocale: "ru_RU", ogLocaleAlt: "uz_UZ", fontSubset: "cyrillic" },
  uz: { out: "uz/index.html", path: "/uz/", base: "../", ogLocale: "uz_UZ", ogLocaleAlt: "ru_RU", fontSubset: "latin" }
};

const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, "assets/js/i18n.js"), "utf8"), sandbox);
const I18N = sandbox.window.I18N;
const template = fs.readFileSync(path.join(__dirname, "template.html"), "utf8");

const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function caseDetails(c) {
  const li = (items) => items.map((x) => `<li>${esc(x)}</li>`).join("");
  return `<div class="case__details" hidden><h4>${esc(c.title)}</h4><p>${esc(c.task)}</p>` +
    `<ul class="case__solution">${li(c.solution)}</ul><ul class="case__stack">${li(c.stack)}</ul></div>`;
}

function jsonLd(dict, url, lang) {
  const services = ["svc.web.title", "svc.mobile.title", "svc.desktop.title", "svc.int.title"];
  return JSON.stringify({
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Person",
        "@id": `${SITE}/#person`,
        name: "Kamol",
        jobTitle: dict["meta.jobTitle"],
        url: SITE + "/",
        image: `${SITE}/assets/img/og.jpg`,
        address: { "@type": "PostalAddress", addressLocality: "Tashkent", addressCountry: "UZ" },
        knowsAbout: ["Django", "FastAPI", "Flutter", "FlutterFlow", "PySide6", "1C OData", "Telegram Bot API", "PostgreSQL", "Firebase"],
        sameAs: ["https://github.com/KamolCoder", "https://timkon.uz"]
      },
      {
        "@type": "ProfessionalService",
        "@id": `${SITE}/#service`,
        name: "kamol.dev",
        description: dict["meta.description"],
        url,
        inLanguage: lang,
        image: `${SITE}/assets/img/og.jpg`,
        founder: { "@id": `${SITE}/#person` },
        areaServed: [{ "@type": "City", name: "Tashkent" }, { "@type": "Country", name: "Uzbekistan" }],
        address: { "@type": "PostalAddress", addressLocality: "Tashkent", addressCountry: "UZ" },
        hasOfferCatalog: {
          "@type": "OfferCatalog",
          name: dict["services.eyebrow"],
          itemListElement: services.map((k) => ({ "@type": "Offer", itemOffered: { "@type": "Service", name: dict[k] } }))
        }
      },
      {
        "@type": "WebSite",
        "@id": `${SITE}/#website`,
        url: SITE + "/",
        name: "kamol.dev",
        inLanguage: ["ru", "uz"]
      }
    ]
  }).replace(/</g, "\\u003c");
}

function render(lang) {
  const cfg = LANGS[lang];
  const dict = I18N[lang];
  const t = (k) => {
    const v = dict[k] ?? I18N.ru[k];
    if (v === undefined) throw new Error(`[${lang}] missing translation: ${k}`);
    return v;
  };
  const url = SITE + cfg.path;
  const preload = [
    `unbounded-${cfg.fontSubset}-800-normal.woff2`,
    `manrope-${cfg.fontSubset}-400-normal.woff2`
  ].map((f) => `  <link rel="preload" href="${cfg.base}assets/fonts/${f}" as="font" type="font/woff2" crossorigin>`).join("\n");

  const vars = {
    lang,
    site: SITE,
    url,
    base: cfg.base,
    ogLocale: cfg.ogLocale,
    ogLocaleAlt: cfg.ogLocaleAlt,
    ruActive: lang === "ru" ? " is-active" : "",
    uzActive: lang === "uz" ? " is-active" : "",
    rotator0: esc(t("hero.rotator")[0])
  };

  let html = template
    // Leaf elements with data-i18n: replace their text content
    .replace(/(<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([^<]*)(<\/\2>)/g, (_, open, _tag, key, _old, close) => open + esc(t(key)) + close)
    .replace(/\{\{case:(\w+)\}\}/g, (_, id) => caseDetails(t("cases")[id]))
    .replace(/\{\{preload\}\}/g, preload)
    .replace(/\{\{jsonld\}\}/g, jsonLd(dict, url, lang))
    .replace(/\{\{([\w.]+)\}\}/g, (_, k) => (k in vars ? vars[k] : esc(t(k))));

  const left = html.match(/\{\{[^}]*\}\}/);
  if (left) throw new Error(`[${lang}] unresolved placeholder ${left[0]}`);
  html = "<!DOCTYPE html>\n<!-- Generated by _build/build.js from _build/template.html — edit the template, not this file. -->\n" +
    html.replace(/^<!DOCTYPE html>\s*/i, "");

  const out = path.join(ROOT, cfg.out);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  console.log(`built ${cfg.out}`);
}

function sitemap() {
  const today = new Date().toISOString().slice(0, 10);
  const alts = Object.entries(LANGS)
    .map(([l, c]) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${SITE}${c.path}"/>`)
    .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}/"/>`)
    .join("\n");
  const urls = Object.values(LANGS)
    .map((c) => `  <url>\n    <loc>${SITE}${c.path}</loc>\n    <lastmod>${today}</lastmod>\n${alts}\n  </url>`)
    .join("\n");
  fs.writeFileSync(path.join(ROOT, "sitemap.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls}\n</urlset>\n`);
  fs.writeFileSync(path.join(ROOT, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`);
  console.log("built sitemap.xml, robots.txt");
}

Object.keys(LANGS).forEach(render);
sitemap();
